-- ─── 045: причина увольнения сотрудника ───────────────────────────────────────
--
-- Увольнение в системе — мягкое: employees.status='archived' + deleted_at=now()
-- (см. archiveEmployee в src/actions/employees.ts). Дата увольнения уже хранится
-- в deleted_at, но причина нигде не фиксировалась — при разборе кадровых вопросов
-- («почему ушёл») информация терялась.
--
-- Добавляем текстовое поле. NULL — законное значение: у ранее уволенных причины нет,
-- и указание причины не делаем обязательным (владелец может уволить без комментария).

ALTER TABLE public.employees
  ADD COLUMN IF NOT EXISTS dismissal_reason TEXT;

COMMENT ON COLUMN public.employees.dismissal_reason IS
  'Причина увольнения (заполняется при архивации сотрудника). NULL — не указана / сотрудник активен.';
