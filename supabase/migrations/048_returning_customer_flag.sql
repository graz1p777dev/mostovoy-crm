-- ─── 048: метка «Постоянный клиент» на записи ─────────────────────────────────
--
-- Менеджер отмечает галочкой, что клиент purchases у нас не впервые.
-- Метка НЕ влияет на расчёт факта: продажи и выручка считаются как раньше.
-- Нужна только для статистики — блок «Постоянные клиенты» на экране МП
-- (сколько из продаж пришлось на постоянных и сколько они принесли).
--
-- Полное разделение воронки на новых/постоянных — задача на будущее;
-- сейчас сознательно только метка и подсчёт.
--
-- DEFAULT false (а не NULL): «не отмечено» = «новый клиент». Трёхзначная
-- логика здесь не нужна и усложнила бы подсчёты.

ALTER TABLE public.consultations
  ADD COLUMN IF NOT EXISTS is_returning_customer BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN public.consultations.is_returning_customer IS
  'Постоянный клиент (покупал ранее). Только для статистики, на расчёт факта не влияет (миграция 048).';

-- Частичный индекс: выборки идут почти всегда по «только постоянные»,
-- полный индекс по булеву полю с перекосом в false был бы бесполезен.
CREATE INDEX IF NOT EXISTS idx_consultations_returning
  ON public.consultations (date)
  WHERE is_returning_customer = true AND deleted_at IS NULL;
