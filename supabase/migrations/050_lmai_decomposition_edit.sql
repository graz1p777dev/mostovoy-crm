-- ─── 050: право decomposition.edit для лид-менеджера ──────────────────────────
--
-- У роли lmai стоял decomposition.edit = false, из-за чего форма ежедневного
-- ввода факта на экране ЛМ не работала для самого ЛМ — сохранять мог только
-- владелец. Это баг: обращения/лиды/встречи брать неоткуда, кроме ручного ввода
-- лид-менеджером, значит право на правку своих данных ему необходимо.
--
-- scope у роли уже 'own' (ЛМ правит только свои дни) — его не трогаем, меняем
-- только can_edit. Идемпотентно: повторный прогон ничего не ломает.
--
-- Роль mp сознательно НЕ трогаем: по решению владельца менеджер продаж ничего
-- не вводит, его факт целиком из «Записей». decomposition.edit у mp остаётся
-- false.

UPDATE public.permissions p
SET    can_edit   = true,
       updated_at = now()
FROM   public.roles r
WHERE  p.role_id  = r.id
  AND  r.name     = 'lmai'
  AND  p.resource = 'decomposition'
  AND  p.can_edit = false;
