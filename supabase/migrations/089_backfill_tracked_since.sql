-- ─── 089: бэкфилл attendance_tracked_since ────────────────────────────────────
--
-- 084 добавил колонку и триггер, но триггер срабатывает только на ВКЛЮЧЕНИЕ учёта.
-- У сотрудников, которым учёт включили в фазе 1, поле осталось NULL — а код табеля
-- переходит с константы ATTENDANCE_LIVE_FROM='2026-07-29' на это поле. Без бэкфилла
-- у них весь месяц стал бы «нет отметки».
--
-- Граница воспроизводится ТОЧНО такой, какой её считал код:
--   максимум из даты запуска учёта и первой реальной записи сотрудника.
-- Если записей нет вовсе — остаётся NULL: у такого сотрудника отсутствие строки
-- по-прежнему ничего не доказывает, и табель покажет пустые клетки, а не пробелы.
--
-- Разовая правка данных: новым сотрудникам дату проставляет триггер из 084.

UPDATE public.employees e
   SET attendance_tracked_since = GREATEST(
         DATE '2026-07-29',
         (SELECT min(a.date) FROM public.attendance a WHERE a.employee_id = e.id)
       )
 WHERE e.attendance_tracked = true
   AND e.attendance_tracked_since IS NULL
   AND EXISTS (SELECT 1 FROM public.attendance a WHERE a.employee_id = e.id);
